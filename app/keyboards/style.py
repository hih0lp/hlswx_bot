"""Цветовая палитра кнопок (ТЗ этапа 2, п. 6.8).

Telegram даёт кнопке ровно три стиля — `primary` (синяя), `success` (зелёная)
и `danger` (красная); если стиль не указан, клиент рисует обычную кнопку.

В макете обычная кнопка белая, а заливкой `#d9d9d9` помечено **только
выбранное или активное** состояние: отмеченные чаты («Шаг 4 · Чаты»),
активный интервал между публикациями, активный тихий режим, активный период
в статистике. Раньше в боте `PRIMARY` стоял почти на каждой кнопке, и из-за
этого выбранное состояние ничем не выделялось.

Отсюда четыре роли. Именами пользуемся везде, `ButtonStyle` в сборщиках
клавиатур напрямую больше не упоминаем — чтобы палитра менялась в одном месте.
"""

from aiogram.enums import ButtonStyle

# Обычный пункт списка и навигация: «← Назад», «🏠 Главное меню», города,
# варианты объёма, разделы профиля и админки. В макете — белая кнопка.
STYLE_PLAIN: ButtonStyle | None = None

# Выбранное / активное состояние: отмеченный чат или город, активное значение
# настройки, активный период. В макете — заливка #d9d9d9.
STYLE_ACTIVE = ButtonStyle.PRIMARY

# Главное действие экрана: «Готово», «Оплатить», «Начать оформление»,
# «Опубликовать», «Изменить текст» на экране ошибки.
STYLE_MAIN = ButtonStyle.SUCCESS

# Необратимое или опасное действие: удалить, отключить, закрыть объявление,
# а также вход в админ-панель.
STYLE_DANGER = ButtonStyle.DANGER
